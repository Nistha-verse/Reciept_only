// Generate the SDK ABI from the exact Hardhat artifact; never hand-edit abi.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { format } from "prettier";
const root = resolve(import.meta.dirname, "../..");
const artifact = JSON.parse(
  readFileSync(
    resolve(
      root,
      "backend/contracts/artifacts/contracts/ReceiptsReviews.sol/ReceiptsReviews.json",
    ),
    "utf8",
  ),
);
const source = `// Generated by backend/scripts/sync-abi.ts from the compiled artifact.\nexport const abi = ${JSON.stringify(artifact.abi)} as const;\n`;
writeFileSync(
  resolve(root, "backend/sdk/src/chain/abi.ts"),
  await format(source, { parser: "typescript" }),
);
console.log("SDK ABI synchronized from Hardhat artifact.");
